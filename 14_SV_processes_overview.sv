SystemVerilog Processes :
- The process or thread is a common concept of an operating system. 
- In an operating system (OS), a process is a program (a piece of code) that is under execution. 
- Similarly in SystemVerilog, process or thread is also a piece of code that executes independently. 
- The process or thread is enclosed in begin..end. If begin..end is not used, each statement acts as a separate process.
- SystemVerilog provides three different ways to start/control processes.
